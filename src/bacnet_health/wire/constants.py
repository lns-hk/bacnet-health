"""BACnet protocol constants (ASHRAE 135, Annex J, clauses 6, 20, 21).

All enumerations are ``IntEnum``. Use :func:`name_of` to turn a raw wire value into a stable, human-readable name such
as ``"read-property"``; values that are not in the enum come back as ``"unknown-<n>"`` (vendor-proprietary ranges,
newer protocol revisions, or garbage).
"""

from __future__ import annotations

import enum
from functools import lru_cache


def name_of(enum_cls: type[enum.IntEnum], value: int | None) -> str:
    """Return the hyphenated lower-case member name for ``value`` or ``"unknown-<value>"``."""
    if value is None:
        return "none"
    return _names(enum_cls).get(int(value), f"unknown-{int(value)}")


@lru_cache(maxsize=None)
def _names(enum_cls: type[enum.IntEnum]) -> dict[int, str]:
    return {m.value: m.name.lower().replace("_", "-") for m in enum_cls}


def value_of(enum_cls: type[enum.IntEnum], name: str | int) -> int:
    """Inverse of :func:`name_of`; accepts ints, member names and ``"unknown-<n>"``. Raises ``ValueError``."""
    if isinstance(name, int):
        return int(name)
    if name.startswith("unknown-"):
        return int(name[8:])
    try:
        return int(enum_cls[name.upper().replace("-", "_")])
    except KeyError:
        raise ValueError(f"{enum_cls.__name__}: unknown name {name!r}") from None


